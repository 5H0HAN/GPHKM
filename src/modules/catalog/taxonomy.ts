export type ListingCategoryName = (typeof LISTING_CATEGORY_NAMES)[number];
export type ListingLanguage = (typeof LISTING_LANGUAGES)[number];
export type ListingLinkType = (typeof LISTING_LINK_TYPES)[number];
export type ListingLinkValidity = (typeof LISTING_LINK_VALIDITIES)[number];

const listingCategorySet: ReadonlySet<string> = new Set(LISTING_CATEGORY_NAMES);

export function isValidListingCategorySelection(value: unknown): value is ListingCategoryName[] {
  return Array.isArray(value) && value.length > 0 && value.length <= LISTING_CATEGORY_LIMIT &&
    value.every((category, index) =>
      typeof category === "string" && listingCategorySet.has(category) && value.indexOf(category) === index,
    );
}

